package migrate

import (
	"fmt"
	"sort"
	"strings"
)

// report is the MIGRATION.md of the output: what was converted, what to
// install where, and what to check.
func report(r *Result, cfg *Legacy, env map[string]string, apps []*app, o Options) []byte {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	cell := func(s string) string {
		if s == "" {
			return "—"
		}
		return strings.ReplaceAll(s, "|", `\|`)
	}

	p("# CYSTEMD v4 → v5 migration\n\n")
	p("Generated by `cystemd migrate`. Every file here is a starting point: review\n")
	p("it, keep it in version control, and follow the steps below. The general\n")
	p("guide is docs/MIGRATION.md in the CYSTEMD repository.\n\n")

	p("## Applications\n\n")
	p("`applications.yaml` holds one Application per `continuous_deployment` entry.\n")
	p("Each runs its unit on every node of its pool (`replicas: 0`, `nodeSelector`),\n")
	p("as v4 did on every host of the pool.\n\n")
	p("| Application | v4 service | Pool | Branch | Values | Secret | Sync |\n")
	p("|---|---|---|---|---|---|---|\n")
	for _, a := range apps {
		src := a.app.Spec.Source
		sync := "manual (v4 autosync off)"
		if a.app.Spec.SyncPolicy.IsAutomated() {
			sync = "automated, self-heal"
		}
		secret := ""
		if len(src.Systemd.Secrets) > 0 {
			secret = src.Systemd.Secrets[0].VaultPath
		}
		p("| `%s` | %s | %s | %s | %s | %s | %s |\n", a.app.Metadata.Name, cell(a.entry.Service), cell(a.entry.Selector),
			cell(src.TargetRevision), cell(strings.TrimPrefix(src.Path+"/"+src.Systemd.ValuesFile, "/")), cell(secret), sync)
	}
	if len(apps) == 0 {
		p("_No continuous_deployment entries were converted._\n")
	}

	p("\n## Hosts\n\n")
	p("`hosts/<host>.hcl` is each host's Nomad client configuration: its node pools\n")
	p("as client meta (`cystemd_selector_<pool>`) and the systemd driver's\n")
	p("allowlists for exactly the units, packages and directories of its\n")
	p("applications.\n\n")
	p("| Host | Pools | Applications |\n|---|---|---|\n")
	for _, h := range r.Hosts {
		p("| %s | %s | %s |\n", cell(h.Name), cell(strings.Join(h.Selectors, ", ")), cell(strings.Join(h.Apps, ", ")))
	}

	p("\n## Files\n\n")
	files := make([]string, 0, len(r.Files))
	for f := range r.Files {
		files = append(files, f)
	}
	sort.Strings(files)
	p("| File | Install |\n|---|---|\n")
	for _, f := range files {
		p("| `%s` | %s |\n", f, installNote(f))
	}

	p("\n## Steps\n\n")
	steps := []string{
		"Set up Consul, Vault and the Nomad ACLs (deploy/README.md, step 1).",
		"Start the server agents with the control plane, merging `control-plane.hcl` into their control plane configuration.",
	}
	if _, ok := r.Files["vault/apply.sh"]; ok {
		steps = append(steps, "Write the applications' Vault policies and roles: `VAULT_ADDR=… VAULT_TOKEN=… vault/apply.sh`.")
	}
	steps = append(steps,
		"On each host, stop the v4 daemon (`systemctl disable --now cystemd`), install the cystemd agent with `deploy/agent/client.hcl` and the host's `hosts/<host>.hcl`, and start it. The units keep running; nothing touches them until their application syncs.",
	)
	if _, ok := r.Files["vault-agent/vault-agent.hcl"]; ok {
		steps = append(steps, "Install the host Vault Agent: `vault-agent/vault-agent.hcl` and `vault-agent/templates/` (see Files).")
	}
	steps = append(steps,
		"Log in (`cystemd login <server>`) and create the applications: `cystemd app create -f applications.yaml`. Automated ones sync at once; to review them first, drop their `syncPolicy` from the file, check `cystemd app diff <name>`, sync with `cystemd app sync <name>`, then `cystemd app set <name> -sync-policy=automated -self-heal`.",
		"The first sync restarts each unit once, so that it runs with the task's environment, secrets and limits (v4 restarted on every change too). Watch them in the UI.",
	)
	for i, s := range steps {
		p("%d. %s\n", i+1, s)
	}

	p("\n## Not carried over\n\n")
	var dropped []string
	if cfg.Version != "" {
		dropped = append(dropped, fmt.Sprintf("`version: %s`: v4 updated its own package. Upgrade the cystemd agent like any Nomad agent (one host at a time).", cell(cfg.Version)))
	}
	if cfg.ListenAddress != "" {
		dropped = append(dropped, "`listen_address`: the API and UI are served on the Nomad agent's HTTP address (`/api/`, `/ui/`).")
	}
	if cfg.Vault.RenewalInterval != "" || cfg.Vault.RenewalFloor != "" || env["VAULT_RENEWAL_INTERVAL"] != "" || env["VAULT_RENEWAL_FLOOR"] != "" {
		dropped = append(dropped, "`vault.renewal_*`: Vault Agent and Nomad renew tokens and leases themselves.")
	}
	if env["VAULT_PATH"] != "" || env["VAULT_ENV_FILE"] != "" {
		dropped = append(dropped, "`VAULT_PATH`/`VAULT_ENV_FILE`: v4's own environment; the agent reads no .env. If other software reads that file, add a template to the host Vault Agent (`vaultagent.EnvTemplate` renders the same KEY=\"value\" format).")
	}
	for _, e := range cfg.ContinuousDeployment {
		if e.Replica > 1 {
			dropped = append(dropped, "`replica` (v4 ignored it): an application runs on every node of its pool; set `replicas: N` to run N instances instead.")
			break
		}
	}
	dropped = append(dropped, "Credentials (`VAULT_ROLE_ID`, `VAULT_SECRET_ID`, `VAULT_TOKEN`, `GIT_SSH_KEY_PRIVATE`, …) are never copied: install them where the files above reference them.")
	for _, d := range dropped {
		p("- %s\n", d)
	}

	p("\n## Warnings\n\n")
	if len(r.Warnings) == 0 {
		p("None.\n")
	}
	for _, w := range r.Warnings {
		p("- %s\n", w)
	}

	if o.KVVersion == 1 {
		p("\nSecrets are read as KV version 1 (`-kv-version=1`).\n")
	} else {
		p("\nSecrets are read as KV version 2 (v4 tried v2, then v1). Pass `-kv-version=1` if their mounts are KV v1.\n")
	}
	return []byte(b.String())
}

func installNote(f string) string {
	switch {
	case f == "applications.yaml":
		return "`cystemd app create -f applications.yaml`"
	case f == "control-plane.hcl":
		return "merge into the control plane configuration on the server hosts"
	case f == "MIGRATION.md":
		return "this report"
	case strings.HasPrefix(f, "hosts/"):
		return "`/etc/cystemd/agent.d/90-migrated.hcl` on that host"
	case f == "vault/apply.sh":
		return "run once with a Vault admin token"
	case strings.HasPrefix(f, "vault/policies/"):
		return "Vault policy (written by vault/apply.sh)"
	case strings.HasPrefix(f, "vault/roles/"):
		return "Vault JWT role (written by vault/apply.sh)"
	case f == "vault-agent/vault-agent.hcl":
		return "`" + "/etc/vault-agent/vault-agent.hcl` on every host that used VAULT_TEMPLATES"
	case strings.HasPrefix(f, "vault-agent/templates/"):
		return "`" + agentTemplateDir + "/` on those hosts"
	}
	return ""
}
