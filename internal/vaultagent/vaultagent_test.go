var update = flag.Bool("update", false, "rewrite the golden deployment example")

func hostConfig() *Config {
	return &Config{
		Vault: Vault{Address: "https://vault.service.consul:8200", CACert: "/etc/vault-agent/ca.pem"},
		AutoAuth: AutoAuth{
			Method: MethodAppRole, MountPath: "auth/approle",
			RoleIDFile: "/etc/vault-agent/role-id", SecretIDFile: "/etc/vault-agent/secret-id",
		},
		APIProxy:                   &APIProxy{Address: "127.0.0.1:8100"},
		ExitOnRetryFailure:         true,
		StaticSecretRenderInterval: "1m",
		Templates: []Template{{
			Contents:    EnvTemplate("kubernetes/myproject/myapplication", 2),
			Destination: "/opt/myapplication/.env",
			Command:     "systemctl try-restart myapplication.service",
		}},
	}
}

// The deployment example is generated, so it always matches the code.
func TestGoldenHostConfig(t *testing.T) {
	got, err := hostConfig().HCL()
	if err != nil {
		t.Fatal(err)
	}
	header := []byte("# Vault Agent on a CYSTEMD host: AppRole auto-auth, the API proxy the\n" +
		"# control plane calls (no token in CYSTEMD), and a template rendering a\n" +
		"# service's .env file. Generated by internal/vaultagent (go test -update).\n\n")
	got = append(header, got...)
	golden := filepath.Join("..", "..", "deploy", "vault-agent", "vault-agent.hcl")
	if *update {
		if err := os.MkdirAll(filepath.Dir(golden), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(golden, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/vaultagent -update)", err)
	}
	if string(got) != string(want) {
		t.Fatalf("deploy/vault-agent/vault-agent.hcl is stale (go test ./internal/vaultagent -update):\n%s", got)
	}
}

func TestHCLQuotingAndValidation(t *testing.T) {
	c := &Config{
		Vault:    Vault{Address: "http://127.0.0.1:8200"},
		AutoAuth: AutoAuth{Method: MethodJWT, MountPath: "auth/jwt-nomad", JWTPath: "/secrets/nomad_vault_agent.jwt", Role: "web"},
		Sinks:    []FileSink{{Path: "/run/vault/token"}},
		Templates: []Template{{
			Contents:    "export A=\"${HOME}\" # {{ with secret \"kv/data/x\" }}{{ .Data.data.a }}{{ end }}\n",
			Destination: "/tmp/out",
		}},
	}
	b, err := c.HCL()
	if err != nil {
		t.Fatal(err)
	}
	// hclwrite aligns the "=" of neighbouring attributes: compare with
	// collapsed whitespace.
	s := strings.Join(strings.Fields(string(b)), " ")
	for _, want := range []string{
		`method "jwt"`, `role = "web"`, `path = "/secrets/nomad_vault_agent.jwt"`, `sink "file"`, `mode = 384`,
		// HCL template sequences are escaped, Go template ones untouched.
		`"export A=\"$${HOME}\" # {{ with secret \"kv/data/x\" }}{{ .Data.data.a }}{{ end }}\n"`,
		`perms = "0600"`,
	} {
		if !strings.Contains(s, want) {
			t.Fatalf("missing %s in:\n%s", want, s)
		}
	}
	bad := []*Config{
		{AutoAuth: AutoAuth{Method: MethodAppRole}},
		{Vault: Vault{Address: "x"}, AutoAuth: AutoAuth{Method: "kerberos"}},
		{Vault: Vault{Address: "x"}, AutoAuth: AutoAuth{Method: MethodTokenFile, TokenFilePath: "/t"}, Templates: []Template{{Destination: "/d"}}},
	}
	for i, c := range bad {
		if _, err := c.HCL(); err == nil {
			t.Fatalf("bad config %d accepted", i)
		}
	}
	if KVDataPath("secret/app/db", 2) != "secret/data/app/db" || KVDataPath("secret/data/app", 2) != "secret/data/app" || KVDataPath("kv/app", 1) != "kv/app" {
		t.Fatal("KVDataPath")
	}
}

// TestRealVaultAgent runs a Vault dev server and a real `vault agent` with
// a generated configuration: AppRole login, a rendered template with its
// change command, and the API proxy serving CYSTEMD's Vault client, which
// holds no token at all.
func TestRealVaultAgent(t *testing.T) {
	if testing.Short() {
		t.Skip("integration test")
	}
	srv, root := testutil.StartVault(t)
	vc, err := vaultapi.NewClient(&vaultapi.Config{Address: srv.URL})
	if err != nil {
		t.Fatal(err)
	}
	vc.SetToken(root)
	ctx := context.Background()
	must := func(err error) {
		t.Helper()
		if err != nil {
			t.Fatal(err)
		}
	}
	must(vc.Sys().EnableAuthWithOptionsWithContext(ctx, "approle", &vaultapi.EnableAuthOptions{Type: "approle"}))
	must(vc.Sys().PutPolicyWithContext(ctx, "cystemd-host", `
path "secret/data/myapp" { capabilities = ["read"] }
path "secret/data/cystemd/repositories/*" { capabilities = ["create", "read", "update", "delete"] }
path "secret/metadata/cystemd/repositories/*" { capabilities = ["delete"] }
`))
	_, err = vc.Logical().WriteWithContext(ctx, "auth/approle/role/host", map[string]any{"token_policies": "cystemd-host", "token_ttl": "20m"})
	must(err)
	rid, err := vc.Logical().ReadWithContext(ctx, "auth/approle/role/host/role-id")
	must(err)
	sid, err := vc.Logical().WriteWithContext(ctx, "auth/approle/role/host/secret-id", nil)
	must(err)
	_, err = vc.KVv2("secret").Put(ctx, "myapp", map[string]any{"DB_USER": "app", "DB_PASS": `p"a$$ {w}`})
	must(err)

	dir := t.TempDir()
	must(os.WriteFile(filepath.Join(dir, "role-id"), []byte(rid.Data["role_id"].(string)), 0o600))
	must(os.WriteFile(filepath.Join(dir, "secret-id"), []byte(sid.Data["secret_id"].(string)), 0o600))
	must(os.WriteFile(filepath.Join(dir, "app.conf.tmpl"), []byte(`user={{ with secret "secret/data/myapp" }}{{ .Data.data.DB_USER }}{{ end }}`+"\n"), 0o600))
	port := testutil.FreePorts(t, 1)[0]
	proxy := fmt.Sprintf("127.0.0.1:%d", port)
	cfg := &Config{
		Vault:    Vault{Address: srv.URL},
		AutoAuth: AutoAuth{Method: MethodAppRole, RoleIDFile: filepath.Join(dir, "role-id"), SecretIDFile: filepath.Join(dir, "secret-id")},
		APIProxy: &APIProxy{Address: proxy},
		Templates: []Template{
			{Contents: EnvTemplate("secret/myapp", 2), Destination: filepath.Join(dir, "out", ".env"),
				Command: "touch " + filepath.Join(dir, "reloaded"), ErrorOnMissingKey: true},
			{Source: filepath.Join(dir, "app.conf.tmpl"), Destination: filepath.Join(dir, "out", "app.conf"), Perms: "0640"},
		},
		StaticSecretRenderInterval: "1s",
	}
	hcl, err := cfg.HCL()
	must(err)
	agent := testutil.StartVaultAgent(t, hcl, func() bool {
		resp, err := http.Get("http://" + proxy + "/v1/sys/health")
		if err != nil {
			return false
		}
		resp.Body.Close()
		return resp.StatusCode == 200
	})

	read := func(name string) string {
		b, _ := os.ReadFile(filepath.Join(dir, "out", name))
		return string(b)
	}
	testutil.Eventually(t, 30*time.Second, func() (bool, string) {
		env := read(".env")
		return strings.Contains(env, `DB_PASS="p\"a$$ {w}"`) && strings.Contains(env, `DB_USER="app"`) && read("app.conf") == "user=app\n",
			".env=" + env + " app.conf=" + read("app.conf") + "\n" + agent.Log()
	})
	if st, err := os.Stat(filepath.Join(dir, "out", ".env")); err != nil || st.Mode().Perm() != 0o600 {
		t.Fatalf(".env mode: %v %v", st, err)
	}
	testutil.Eventually(t, 10*time.Second, func() (bool, string) {
		_, err := os.Stat(filepath.Join(dir, "reloaded"))
		return err == nil, "change command did not run"
	})

	// A secret change re-renders the file and runs the command again.
	must(os.Remove(filepath.Join(dir, "reloaded")))
	_, err = vc.KVv2("secret").Put(ctx, "myapp", map[string]any{"DB_USER": "app2", "DB_PASS": "x"})
	must(err)
	testutil.Eventually(t, 30*time.Second, func() (bool, string) {
		_, err := os.Stat(filepath.Join(dir, "reloaded"))
		return err == nil && strings.Contains(read(".env"), `DB_USER="app2"`), read(".env")
	})

	// CYSTEMD's Vault client through the proxy: no token configured.
	c, err := vault.New(vault.Config{AgentAddress: "http://" + proxy})
	must(err)
	must(c.Write(ctx, "cystemd/repositories/abc", map[string]any{"username": "git", "password": "s3cret"}))
	got, err := c.Read(ctx, "cystemd/repositories/abc")
	must(err)
	if got["password"] != "s3cret" {
		t.Fatalf("read through the agent: %v", got)
	}
	st, err := c.Health(ctx)
	if err != nil || !st.ViaAgent || st.Sealed {
		t.Fatalf("health through the agent: %+v %v", st, err)
	}
	// The policy is enforced with the agent's token, not a root token.
	if _, err := c.Read(ctx, "other/secret"); err == nil {
		t.Fatal("read outside the policy succeeded")
	}
}
